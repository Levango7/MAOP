class TestLicenseManagerValidate:
    def test_validate_valid_license(self, manager: LicenseManager):
        rec = manager.create_license(customer="ACME", expires_at=_future_iso(365))
        result = manager.validate_license(rec.license_key)
        assert result["valid"] is True
        assert result["reason"] == "ok"
        assert result["info"]["customer"] == "ACME"

    def test_validate_expired_license(self, manager: LicenseManager):
        rec = manager.create_license(customer="ACME", expires_at=_past_iso(30))
        result = manager.validate_license(rec.license_key)
        assert result["valid"] is False
        assert result["reason"] == "expired"

    def test_validate_grace_period_license(self, manager: LicenseManager):
        # Expired 2 days ago — within the 7-day grace period.
        expires_dt = datetime.now(timezone.utc) - timedelta(days=2)
        rec = manager.create_license(customer="ACME", expires_at=expires_dt.isoformat())
        result = manager.validate_license(rec.license_key)
        assert result["valid"] is True
        assert result["reason"] == "in_grace_period"

    def test_validate_revoked_license(self, manager: LicenseManager):
        rec = manager.create_license(customer="ACME", expires_at=_future_iso(365))
        manager.revoke_license(rec.license_id, reason="policy violation")
        result = manager.validate_license(rec.license_key)
        assert result["valid"] is False
        assert "revoked" in result["reason"]

    def test_validate_tampered_signature(self, manager: LicenseManager):
        import base64

        rec = manager.create_license(customer="ACME", expires_at=_future_iso(365))
        # Flip a bit in the signature portion.
        payload_b64, sig_b64 = rec.license_key[len("MAOP-ENT-"):].rsplit(".", 1)
        sig = bytearray(base64.urlsafe_b64decode(sig_b64 + "=="))
        sig[0] ^= 0x01
        tampered_sig = base64.urlsafe_b64encode(bytes(sig)).rstrip(b"=").decode("ascii")
        tampered = f"MAOP-ENT-{payload_b64}.{tampered_sig}"
        result = manager.validate_license(tampered)
        assert result["valid"] is False
        assert "signature_invalid" in result["reason"]

    def test_validate_malformed_key(self, manager: LicenseManager):
        result = manager.validate_license("not-a-license")
        assert result["valid"] is False
        assert "signature_invalid" in result["reason"]

    def test_validate_empty_key(self, manager: LicenseManager):
        result = manager.validate_license("")
        assert result["valid"] is False


