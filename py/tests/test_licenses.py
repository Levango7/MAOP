def _future_iso(days: int = 365) -> str:
    """Return an ISO datetime string `days` days in the future."""
    return (datetime.now(timezone.utc) + timedelta(days=days)).strftime("%Y-%m-%d")


def _past_iso(days: int = 30) -> str:
    """Return an ISO date string `days` days in the past."""
    return (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%d")


