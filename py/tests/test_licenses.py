class TestDatetimeParsing:
    def test_parse_yyyy_mm_dd(self):
        dt = LicenseManager._parse_datetime("2027-12-31")
        assert dt.year == 2027
        assert dt.month == 12
        assert dt.day == 31
        assert dt.hour == 23
        assert dt.minute == 59
        assert dt.second == 59
        assert dt.tzinfo == timezone.utc

    def test_parse_iso_with_z(self):
        dt = LicenseManager._parse_datetime("2027-12-31T10:00:00Z")
        assert dt.hour == 10
        assert dt.tzinfo == timezone.utc

    def test_parse_iso_with_offset(self):
        dt = LicenseManager._parse_datetime("2027-12-31T10:00:00+02:00")
        assert dt.tzinfo == timezone.utc
        # 10:00 +02:00 == 08:00 UTC
        assert dt.hour == 8

    def test_parse_datetime_object(self):
        original = datetime(2027, 12, 31, 10, 0, 0, tzinfo=timezone.utc)
        dt = LicenseManager._parse_datetime(original)
        assert dt == original

    def test_parse_naive_datetime_assumed_utc(self):
        original = datetime(2027, 12, 31, 10, 0, 0)  # noqa: DTZ001
        dt = LicenseManager._parse_datetime(original)
        assert dt.tzinfo == timezone.utc
        assert dt.hour == 10