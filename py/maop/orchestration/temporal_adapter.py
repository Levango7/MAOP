"""Temporal 后端适配器 —— M-X2 M0（编译 + dev server 连通）.

章程落点（ROADMAP「M-X2 多后端编排器适配」）：``WorkflowDef`` DAG →
Temporal workflow 定义编译 + 可跑的 demo；**不承诺生产集成**（企业侧
运行时供给未定）。

设计口径：
- temporalio 是**可选依赖**（同 operator 的 kopf/kubernetes 先例，不进
  pyproject）：``run`` 需要它，``compile_workflow`` 纯文本生成、不需要。
  模块级 ``@workflow.defn``/``@activity.defn`` 用**定义期占位**兜底
  （temporalio 缺席时恒等装饰器，测试机/CI 可 import），``run`` 入口由
  ``_require_temporalio`` 再做真检——占位产物只用于定义面，不会上线；
- 运行体是**数据驱动的通用 workflow**（``MaopDagWorkflow``：DAG 结构作为
  入参 payload）——真 temporalio 拒绝本地类上的 ``@workflow.run``（dev
  server 实证），动态构造类又是注入面（Mimosa 高危实拦），故不按名字
  生成类也不 exec；``artifact`` 文本是编译产物的静态展开**审阅件**；
- 不读环境变量（config-drift 棘轮零增量）——server 地址/namespace/队列
  全部构造参数，由调用方（demo 脚本/未来接线层）显式给值；
- 节点执行体经 ``executor`` 注入（M0 demo 为记录型 executor；MAOP agent
  调度接入 = 生产集成里程碑）。
"""

from __future__ import annotations

import ast
import asyncio
import re
from collections.abc import Callable
from datetime import timedelta
from typing import Any

from maop.config.loader import WorkflowDef
from maop.orchestration.base import (
    CompiledWorkflow,
    WorkflowNode,
    nodes_from_steps,
    plan_levels,
)


class _DefinitionPlaceholder:
    """temporalio 缺席时的定义期占位：``@mod.x``/``@mod.x(...)`` 皆恒等."""

    def __getattr__(self, name: str) -> Any:
        def _deco(*args: Any, **kwargs: Any) -> Any:
            if len(args) == 1 and callable(args[0]) and not kwargs:
                return args[0]
            return lambda fn: fn

        return _deco


try:  # 可选依赖（定义面）：缺席时用恒等占位，run 前真检见 _require_temporalio
    from temporalio import activity, workflow
except ImportError:
    activity = _DefinitionPlaceholder()  # type: ignore[no-redef,assignment]
    workflow = _DefinitionPlaceholder()  # type: ignore[no-redef,assignment]

_BACKEND = "temporal"
DEFAULT_SERVER_ADDRESS = "localhost:7233"  # temporal server start-dev 默认口
DEFAULT_NAMESPACE = "default"
DEFAULT_TASK_QUEUE = "maop-m0"
ACTIVITY_NAME = "maop_node"

_NON_IDENT = re.compile(r"[^0-9a-zA-Z_]")


def _require_temporalio() -> None:
    try:
        import temporalio  # noqa: F401
    except ImportError as exc:
        raise RuntimeError(
            "maop.orchestration.temporal_adapter requires 'temporalio' — "
            "install with 'pip install temporalio'（可选依赖，同 kopf/"
            "kubernetes 先例，不进 pyproject）"
        ) from exc


def _workflow_class_name(name: str) -> str:
    """名字 → 合法 Python 类名（纯函数，确定性与幂等由此保证）."""
    cleaned = _NON_IDENT.sub("_", name).strip("_") or "workflow"
    if cleaned[0].isdigit():
        cleaned = f"_{cleaned}"
    return f"Maop{cleaned}"


def _render_workflow_source(
    name: str, nodes: tuple[WorkflowNode, ...], levels: tuple[tuple[str, ...], ...]
) -> str:
    """生成 Temporal workflow **定义文本**（审阅/审计用编译产物）.

    节点/层序以字面量注入（repr，确定性顺序）。文本与运行体（
    ``_build_runtime``）表达同一份 DAG——本函数不做执行载体。
    """
    nodes_literal = {
        n.step_id: {
            "step_id": n.step_id, "agent": n.agent,
            "task": n.task, "timeout_s": n.timeout_s,
        }
        for n in nodes
    }
    cls = _workflow_class_name(name)
    return (
        "# Auto-generated by maop.orchestration.temporal_adapter (M-X2 M0)"
        " — do not edit.\n"
        '"""Temporal workflow compiled from a MAOP WorkflowDef DAG."""\n'
        "import asyncio\n"
        "from datetime import timedelta\n"
        "\n"
        "from temporalio import activity, workflow\n"
        "\n"
        f"NODES: dict[str, dict] = {nodes_literal!r}\n"
        f"LEVELS: tuple[tuple[str, ...], ...] = {levels!r}\n"
        "\n"
        f'@activity.defn(name="{ACTIVITY_NAME}")\n'
        "async def maop_node(node: dict) -> dict:\n"
        '    return {"step_id": node["step_id"], "status": node["task"]}\n'
        "\n"
        "\n"
        f"@workflow.defn(name={name!r})\n"
        f"class {cls}:\n"
        "    @workflow.run\n"
        "    async def run(self) -> dict:\n"
        "        results: dict = {}\n"
        "        for level in LEVELS:\n"
        "            outcomes = await asyncio.gather(\n"
        "                *[\n"
        "                    workflow.execute_activity(\n"
        f'                        "{ACTIVITY_NAME}",\n'
        "                        args=[NODES[nid]],\n"
        "                        start_to_close_timeout=timedelta(\n"
        '                            seconds=NODES[nid]["timeout_s"]),\n'
        "                    )\n"
        "                    for nid in level\n"
        "                ]\n"
        "            )\n"
        f"            results.update(zip(level, outcomes))\n"
        f'        return {{"workflow": {name!r}, "levels": len(LEVELS),'
        f' "nodes": results}}\n'
    )


class TemporalAdapter:
    """``OrchestrationAdapter`` 的 Temporal 实现（M0：编译 + dev server 连通）."""

    backend = _BACKEND

    def __init__(
        self,
        *,
        server_address: str = DEFAULT_SERVER_ADDRESS,
        namespace: str = DEFAULT_NAMESPACE,
        task_queue: str = DEFAULT_TASK_QUEUE,
    ) -> None:
        self.server_address = server_address
        self.namespace = namespace
        self.task_queue = task_queue

    def compile_workflow(
        self, workflow: WorkflowDef, *, name: str = ""
    ) -> CompiledWorkflow:
        """WorkflowDef → CompiledWorkflow（纯函数、幂等、不触网）.

        ``name`` 缺省取 WorkflowDef 的 ``description`` 前缀，仍空则
        ``maop-workflow``。
        """
        non_empty = name or (workflow.description or "").strip() or "maop-workflow"
        levels = plan_levels(workflow.steps)
        nodes = nodes_from_steps(workflow.steps)
        artifact = _render_workflow_source(non_empty, nodes, levels)
        ast.parse(artifact)  # 语法哨兵：产物必须是合法 Python
        return CompiledWorkflow(
            backend=_BACKEND, name=non_empty, nodes=nodes,
            levels=levels, artifact=artifact,
        )

    async def run(
        self,
        compiled: CompiledWorkflow,
        *,
        executor: Callable[[WorkflowNode], dict[str, Any]] | None = None,
        timeout_s: float | None = None,
    ) -> dict[str, Any]:
        """把编译产物对应的 workflow 在 Temporal server 上真实跑一次.

        连接 → 进程内 Worker（注册模块级 ``MaopDagWorkflow`` / ``maop_node``，
        见其 docstring：结构作为入参 payload）→ 启动 → 等待终值。
        ``executor`` 注入节点执行体（None 时活动返回 no-executor 占位——
        连通性仍被证明）。M0 单进程语义：``EXECUTOR`` 是模块级注入点，
        同进程并发 run 会互相覆盖（生产接线属后续里程碑，届时改 per-worker
        注册）。
        """
        _require_temporalio()
        from temporalio.client import Client
        from temporalio.worker import Worker

        global EXECUTOR
        EXECUTOR = _executor_bridge(executor) if executor is not None else None

        payload = {
            "name": compiled.name,
            "nodes": {
                n.step_id: {
                    "step_id": n.step_id, "agent": n.agent,
                    "task": n.task, "timeout_s": n.timeout_s,
                }
                for n in compiled.nodes
            },
            "levels": [list(level) for level in compiled.levels],
        }
        client = await Client.connect(
            self.server_address, namespace=self.namespace
        )
        async with Worker(
            client,
            task_queue=self.task_queue,
            workflows=[MaopDagWorkflow],
            activities=[maop_node_activity],
        ):
            handle = await client.start_workflow(
                MaopDagWorkflow.run,
                payload,
                id=f"{compiled.name}-{id(compiled) & 0xFFFFFF:06x}",
                task_queue=self.task_queue,
            )
            return await asyncio.wait_for(handle.result(), timeout=timeout_s)


#: 节点执行体注入点（worker 侧在启动前赋值；None → 活动返回占位）。
#: M0 单进程语义：同进程并发 run 会互相覆盖（生产接线属后续里程碑）。
EXECUTOR: Callable[[dict], dict] | None = None


@activity.defn(name=ACTIVITY_NAME)
async def maop_node_activity(node: dict) -> dict:
    """单节点执行活动：dict 进出（Temporal 序列化边界），桥回 executor."""
    if EXECUTOR is None:
        return {"step_id": node["step_id"], "status": "no-executor"}
    return EXECUTOR(node)


@workflow.defn(name="MaopDagWorkflow")
class MaopDagWorkflow:
    """数据驱动的通用 DAG workflow（所有编译产物共用这一个 defn）.

    真 temporalio 拒绝**本地类**上的 ``@workflow.run``（sandbox 限制，
    dev server 实证），且动态构造类属注入面（Mimosa 高危实拦）——因此
    不按名字生成类，而是把 DAG 结构（nodes/levels）作为 workflow **入参
    payload**（Temporal 习惯用法：结构即数据）。``artifact`` 文本仍是
    编译产物的静态展开审阅件，与本类表达同一份 DAG。
    """

    @workflow.run
    async def run(self, payload: dict) -> dict:
        nodes: dict[str, dict] = payload["nodes"]
        results: dict = {}
        for level in payload["levels"]:
            outcomes = await asyncio.gather(
                *[
                    workflow.execute_activity(
                        ACTIVITY_NAME,
                        args=[nodes[nid]],
                        start_to_close_timeout=timedelta(
                            seconds=nodes[nid]["timeout_s"]
                        ),
                    )
                    for nid in level
                ]
            )
            results.update(zip(level, outcomes))
        return {
            "workflow": payload["name"],
            "levels": len(payload["levels"]),
            "nodes": results,
        }


def _executor_bridge(
    executor: Callable[[WorkflowNode], dict[str, Any]],
) -> Callable[[dict], dict]:
    """活动拿 dict（序列化边界）；这里桥回 WorkflowNode 语义."""

    def _run(node_dict: dict) -> dict:
        return executor(
            WorkflowNode(
                step_id=str(node_dict["step_id"]),
                agent=str(node_dict["agent"]),
                task=str(node_dict["task"]),
                timeout_s=int(node_dict["timeout_s"]),
            )
        )

    return _run
